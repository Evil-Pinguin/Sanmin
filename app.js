function formatErrorCount(count) {
  const lastTwoDigits = count % 100;
  const lastDigit = count % 10;
  if (lastTwoDigits >= 11 && lastTwoDigits <= 14) return `${count} ошибок`;
  if (lastDigit === 1) return `${count} ошибка`;
  if (lastDigit >= 2 && lastDigit <= 4) return `${count} ошибки`;
  return `${count} ошибок`;
}

function getResultMessage(percent) {
  if (percent >= 90) return { title: "Отличный результат", text: "Вы уверенно ориентируетесь в теме санитарно-эпидемиологического благополучия." };
  if (percent >= 70) return { title: "Хорошая база", text: "Основные положения вам знакомы. Разберите ошибки, чтобы закрепить детали." };
  if (percent >= 50) return { title: "Неплохой старт", text: "Вы уже знаете часть материала. Пояснения помогут закрыть пробелы." };
  return { title: "Есть что повторить", text: "Просмотрите разбор ошибок и попробуйте пройти тест ещё раз." };
}

